fun main() {
    println("variables")

    // val for static values
    val x = 52
    val age: Int = 99
    val weight: Double = 214.58
    val isLearning: Boolean = true
    println("x: $x")
    println("age: $age")
    println("weight: $weight")
    println("isLearning: $isLearning")

    // var for redefinable variables
    var name : String = "Jeferson"
    name += " Souza"
    println("name: $name")

    // automatic type
    var username = "jooj"
    println("username : $username")

}